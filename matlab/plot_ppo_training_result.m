clear;
clc;
close all;

paths = project_paths();

load( ...
    fullfile(paths.Models,"ppo_cartpole_trained.mat"), ...
    "trainingStats");

episodes = trainingStats.EpisodeIndex;
episodeReward = trainingStats.EpisodeReward;
averageReward = trainingStats.AverageReward;

figure( ...
    "Name","Final PPO Training Result", ...
    "Position",[100 100 1200 650]);

plot( ...
    episodes, ...
    episodeReward, ...
    "Color",[0.25 0.75 0.85], ...
    "LineWidth",0.8);

hold on;

plot( ...
    episodes, ...
    averageReward, ...
    "Color",[0.1 0.35 0.95], ...
    "LineWidth",2.2);

yline( ...
    450, ...
    "r--", ...
    "Stop criterion = 450", ...
    "LineWidth",1.5);

grid on;
xlabel("Episode");
ylabel("Reward");
title("PPO Training Convergence");
legend( ...
    "Episode reward", ...
    "Moving average reward", ...
    "Location","northwest");

finalEpisode = episodes(end);
finalAverage = averageReward(end);

subtitle(sprintf( ...
    "Stopped automatically at episode %d, average reward %.2f", ...
    finalEpisode, ...
    finalAverage));

outputPath = fullfile( ...
    paths.Images, ...
    "ppo_training_result.png");

exportgraphics(gcf,outputPath,"Resolution",180);

fprintf("Final episode: %d\n",finalEpisode);
fprintf("Final average reward: %.4f\n",finalAverage);
fprintf("Saved: %s\n",outputPath);
